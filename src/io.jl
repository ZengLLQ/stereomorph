# StereoMorph — File I/O & Formats (SDF / MOL / XYZ) Module

module MolecularIO

using Printf
using ..Types

export write_xyz, read_xyz, write_sdf, read_mol, write_ensemble_xyz

"""
    write_xyz(io::IO, mol::Molecule, coords::Matrix{Float64}, comment::String="Generated by StereoMorph.jl")

Writes molecular coordinates to an IO stream in standard XYZ Cartesian format.
"""
function write_xyz(io::IO, mol::Molecule, coords::Matrix{Float64}, comment::String="Generated by StereoMorph.jl")
    n = length(mol.atoms)
    println(io, n)
    println(io, comment)
    for i in 1:n
        sym = mol.atoms[i].symbol
        @printf(io, "%-3s  %12.6f  %12.6f  %12.6f\n", sym, coords[1, i], coords[2, i], coords[3, i])
    end
end

function write_xyz(filepath::String, mol::Molecule, coords::Matrix{Float64}, comment::String="Generated by StereoMorph.jl")
    open(filepath, "w") do f
        write_xyz(f, mol, coords, comment)
    end
end

"""
    write_ensemble_xyz(filepath::String, mol::Molecule, conformers::Vector{Conformation})

Writes a multi-conformer trajectory in XYZ format.
"""
function write_ensemble_xyz(filepath::String, mol::Molecule, conformers::Vector{Conformation})
    open(filepath, "w") do f
        for (idx, conf) in enumerate(conformers)
            comment = @sprintf("Conformation %d | Energy: %.4f kcal/mol | Violations: %d", idx, conf.energy, conf.violations)
            write_xyz(f, mol, conf.coords, comment)
        end
    end
end

"""
    read_xyz(filepath::String)::Tuple{Vector{String}, Matrix{Float64}}

Parses a standard XYZ file and returns (atom_symbols, coords_matrix).
"""
function read_xyz(filepath::String)::Tuple{Vector{String}, Matrix{Float64}}
    lines = readlines(filepath)
    if length(lines) < 3
        error("Invalid XYZ file format: fewer than 3 lines.")
    end

    n = parse(Int, strip(lines[1]))
    symbols = String[]
    coords = zeros(Float64, 3, n)

    for i in 1:n
        tokens = split(strip(lines[i + 2]))
        if length(tokens) < 4
            error("Invalid XYZ atom line $i: $(lines[i + 2])")
        end
        push!(symbols, tokens[1])
        coords[1, i] = parse(Float64, tokens[2])
        coords[2, i] = parse(Float64, tokens[3])
        coords[3, i] = parse(Float64, tokens[4])
    end

    return symbols, coords
end

"""
    write_sdf(io::IO, mol::Molecule, coords::Matrix{Float64}, title::String=mol.name)

Writes a molecule in MDL MOL V2000 format.
"""
function write_sdf(io::IO, mol::Molecule, coords::Matrix{Float64}, title::String=mol.name)
    n_atoms = length(mol.atoms)
    n_bonds = length(mol.bonds)

    # Header block (3 lines)
    println(io, title)
    println(io, "  StereoMorph.jl 3D Conformer")
    println(io, "")

    # Counts line: aaabbblllfffcccsssxxxrrrpppiii999 V2000
    @printf(io, "%3d%3d  0  0  0  0  0  0  0  0999 V2000\n", n_atoms, n_bonds)

    # Atom block: x y z symbol mass_diff charge stereo ...
    for i in 1:n_atoms
        sym = mol.atoms[i].symbol
        @printf(io, "%10.4f%10.4f%10.4f %-3s 0  0  0  0  0  0  0  0  0%3d  0  0\n",
                coords[1, i], coords[2, i], coords[3, i], sym, i)
    end

    # Bond block: 111222tttsss ...
    for b in mol.bonds
        order_int = round(Int, b.order)
        order_int = clamp(order_int, 1, 4)
        if b.aromatic
            order_int = 4 # 4 = aromatic in V2000
        end
        @printf(io, "%3d%3d%3d  0  0  0  0\n", b.atom1, b.atom2, order_int)
    end

    # End marker
    println(io, "M  END")
    println(io, "\$\$\$\$")
end

function write_sdf(filepath::String, mol::Molecule, coords::Matrix{Float64}, title::String=mol.name)
    open(filepath, "w") do f
        write_sdf(f, mol, coords, title)
    end
end

"""
    read_mol(filepath::String)::Tuple{Molecule, Matrix{Float64}}

Parses an MDL MOL V2000 file into a Molecule structure and initial 3D coordinates.
"""
function read_mol(filepath::String)::Tuple{Molecule, Matrix{Float64}}
    lines = readlines(filepath)
    if length(lines) < 4
        error("Invalid MOL file: too short.")
    end

    title = strip(lines[1])
    counts_line = lines[4]
    n_atoms = parse(Int, strip(counts_line[1:3]))
    n_bonds = parse(Int, strip(counts_line[4:6]))

    atoms = Atom[]
    coords = zeros(Float64, 3, n_atoms)

    line_idx = 5
    for i in 1:n_atoms
        ln = lines[line_idx]
        x = parse(Float64, strip(ln[1:10]))
        y = parse(Float64, strip(ln[11:20]))
        z = parse(Float64, strip(ln[21:30]))
        sym = strip(ln[32:34])

        coords[1, i] = x
        coords[2, i] = y
        coords[3, i] = z

        info = get_element_info(sym)
        push!(atoms, Atom(i, sym, info[1], info[2], info[3], info[4], SP3, 0))
        line_idx += 1
    end

    bonds = Bond[]
    for _ in 1:n_bonds
        ln = lines[line_idx]
        a1 = parse(Int, strip(ln[1:3]))
        a2 = parse(Int, strip(ln[4:6]))
        o_int = parse(Int, strip(ln[7:9]))
        arom = (o_int == 4)
        order = arom ? 1.5 : Float64(o_int)
        push!(bonds, Bond(a1, a2, order, arom))
        line_idx += 1
    end

    mol = Molecule(title, atoms, bonds)
    return mol, coords
end

end # module MolecularIO
